"""
Module 3: Mask-Level Erasure & Extraction Engine (The Discrepancy Engine)
Removes motion generated by Known Objects (Stream B) from the Binary Motion Mask (Stream A)
by erasing padded bounding boxes (YOLO_PAD_PX = 15), then extracts candidate unknown bounding boxes.
Adheres strictly to fyp_architecture_final_object.md Section 3 Module 3.
"""

import time
from typing import List, Optional, Tuple, Union, Any
import cv2
import numpy as np

from module_3.config import Module3Config, CandidateUnknownBox, Module3FrameResult


class MaskErasureEngine:
    """
    Discrepancy Engine:
    1. Expands Stream B known bounding boxes by padding (YOLO_PAD_PX = 15).
    2. Erases known regions on the binary motion mask by painting them black (0).
    3. Extracts surviving motion contours using cv2.findContours.
    4. Filters out contours smaller than min_contour_area (500 px).
    5. Outputs Candidate Unknown Bounding Boxes [U, 5] formatted as (x1, y1, x2, y2, confidence).
    """

    def __init__(self, config: Optional[Module3Config] = None):
        self.config = config or Module3Config()
        if self.config.morph_close:
            self.morph_kernel = cv2.getStructuringElement(
                cv2.MORPH_RECT, self.config.morph_close_kernel_size
            )
        else:
            self.morph_kernel = None

    def process(
        self,
        motion_mask: np.ndarray,
        known_boxes: Union[List[Any], np.ndarray],
        frame_index: int = 0
    ) -> Module3FrameResult:
        """
        Executes mask-level erasure and candidate unknown extraction.

        Args:
            motion_mask: (H, W) uint8 binary mask from Stream A (values in {0, 255}).
            known_boxes: List of KnownBoundingBox objects or [K, 4] numpy array of (x1, y1, x2, y2).
            frame_index: Integer index of the current frame.

        Returns:
            Module3FrameResult containing erased mask, candidate boxes, and [U, 5] matrix.
        """
        t0 = time.perf_counter()

        if motion_mask is None or motion_mask.size == 0:
            return Module3FrameResult(
                frame_index=frame_index,
                erased_mask=np.zeros((0, 0), dtype=np.uint8),
                boxes=[],
                box_matrix=np.empty((0, 5), dtype=np.float32),
                erased_known_count=0,
                processing_time_ms=0.0
            )

        h, w = motion_mask.shape[:2]
        erased_mask = motion_mask.copy()

        # Extract coordinates from input
        boxes_coords: List[Tuple[int, int, int, int]] = []
        if isinstance(known_boxes, np.ndarray):
            if known_boxes.size > 0 and known_boxes.ndim == 2 and known_boxes.shape[1] >= 4:
                for row in known_boxes:
                    boxes_coords.append((int(row[0]), int(row[1]), int(row[2]), int(row[3])))
        elif isinstance(known_boxes, (list, tuple)):
            for b in known_boxes:
                if hasattr(b, "as_xyxy"):
                    boxes_coords.append(b.as_xyxy())
                elif hasattr(b, "x1") and hasattr(b, "y1") and hasattr(b, "x2") and hasattr(b, "y2"):
                    boxes_coords.append((int(b.x1), int(b.y1), int(b.x2), int(b.y2)))
                elif isinstance(b, (list, tuple)) and len(b) >= 4:
                    boxes_coords.append((int(b[0]), int(b[1]), int(b[2]), int(b[3])))

        # 1. Padding & 2. Erasure (YOLO_PAD_PX = 15)
        erased_count = 0
        pad_px = self.config.pad_px
        for x1, y1, x2, y2 in boxes_coords:
            bw = max(0, x2 - x1)
            bh = max(0, y2 - y1)
            if bw == 0 or bh == 0:
                continue

            pad_x = max(pad_px, int(round(bw * self.config.dilation_margin)))
            pad_y = max(pad_px, int(round(bh * self.config.dilation_margin)))

            px1 = max(0, x1 - pad_x)
            py1 = max(0, y1 - pad_y)
            px2 = min(w, x2 + pad_x)
            py2 = min(h, y2 + pad_y)

            # Paint the dilated region black (0) on the binary motion mask
            erased_mask[py1:py2, px1:px2] = 0
            erased_count += 1

        # 3. Morphological Closing to bridge fractured components of the same object
        if self.config.morph_close and self.morph_kernel is not None:
            erased_mask = cv2.morphologyEx(
                erased_mask,
                cv2.MORPH_CLOSE,
                self.morph_kernel
            )

        # 4. Contour Extraction on residual motion mask
        contours, _ = cv2.findContours(
            erased_mask,
            cv2.RETR_EXTERNAL,
            cv2.CHAIN_APPROX_SIMPLE
        )

        candidate_boxes: List[CandidateUnknownBox] = []

        # 5. Area Filtering & Bounding Box Generation
        for cnt in contours:
            area = float(cv2.contourArea(cnt))
            if area < self.config.min_contour_area:
                continue

            cx_box, cy_box, cw, ch = cv2.boundingRect(cnt)
            bx1 = cx_box
            by1 = cy_box
            bx2 = min(w, cx_box + cw)
            by2 = min(h, cy_box + ch)

            # Calculate centroid
            moments = cv2.moments(cnt)
            if moments["m00"] != 0:
                cx = int(moments["m10"] / moments["m00"])
                cy = int(moments["m01"] / moments["m00"])
            else:
                cx = bx1 + cw // 2
                cy = by1 + ch // 2

            box = CandidateUnknownBox(
                x1=bx1,
                y1=by1,
                x2=bx2,
                y2=by2,
                confidence=self.config.tracker_confidence,
                area=area,
                centroid=(cx, cy),
                contour=cnt
            )
            candidate_boxes.append(box)

        # 6. Spatial Proximity Merging
        if self.config.merge_proximity_px > 0 and len(candidate_boxes) > 1:
            candidate_boxes = self._merge_proximate_boxes(
                candidate_boxes, self.config.merge_proximity_px
            )

        candidate_boxes.sort(key=lambda b: b.area, reverse=True)
        matrix_rows = [
            [float(b.x1), float(b.y1), float(b.x2), float(b.y2), float(b.confidence)]
            for b in candidate_boxes
        ]
        if len(matrix_rows) > 0:
            box_matrix = np.array(matrix_rows, dtype=np.float32)
        else:
            box_matrix = np.empty((0, 5), dtype=np.float32)

        elapsed_ms = (time.perf_counter() - t0) * 1000.0

        return Module3FrameResult(
            frame_index=frame_index,
            erased_mask=erased_mask,
            boxes=candidate_boxes,
            box_matrix=box_matrix,
            erased_known_count=erased_count,
            processing_time_ms=elapsed_ms
        )

    def _merge_proximate_boxes(
        self, boxes: List[CandidateUnknownBox], proximity: int
    ) -> List[CandidateUnknownBox]:
        """
        Merges candidate boxes that overlap or are situated within proximity pixels of each other.
        """
        if len(boxes) <= 1:
            return boxes

        merged: List[CandidateUnknownBox] = []
        unmerged = list(boxes)

        while unmerged:
            curr = unmerged.pop(0)
            has_merged = False
            for idx, other in enumerate(unmerged):
                x_near = not (curr.x2 + proximity < other.x1 or curr.x1 - proximity > other.x2)
                y_near = not (curr.y2 + proximity < other.y1 or curr.y1 - proximity > other.y2)

                if x_near and y_near:
                    nx1 = min(curr.x1, other.x1)
                    ny1 = min(curr.y1, other.y1)
                    nx2 = max(curr.x2, other.x2)
                    ny2 = max(curr.y2, other.y2)
                    cx = (nx1 + nx2) // 2
                    cy = (ny1 + ny2) // 2
                    area = float((nx2 - nx1) * (ny2 - ny1))
                    combined = CandidateUnknownBox(
                        x1=nx1,
                        y1=ny1,
                        x2=nx2,
                        y2=ny2,
                        confidence=self.config.tracker_confidence,
                        area=area,
                        centroid=(cx, cy)
                    )
                    unmerged.pop(idx)
                    unmerged.append(combined)
                    has_merged = True
                    break
            if not has_merged:
                merged.append(curr)

        return merged
